-- =====================================================================
-- Buffalo Machines Staff Hub: sales and invoices (run once)
-- Paste this whole file into Supabase > SQL Editor > New query > Run.
-- Safe to run more than once. Does not delete or change any existing data.
--
-- What it adds:
--   1. models.price: selling price EXCLUDING VAT for each machine/accessory.
--      Everyone signed in can see prices; only managers can change them
--      (existing models rules). Price changes appear in the activity log.
--   2. company_settings: one row of company details printed on invoices
--      (address, bank details, VAT number...). Everyone signed in can read
--      it (it goes on every invoice); only managers can change it.
--      Bank details are typed in on the website, never stored in the code.
--   3. invoices: one row per invoice so numbers run in order (BM-1001,
--      BM-1002...) and never repeat. Stores the date, items, totals and who
--      made it. NO customer details are stored, by design.
--      Everyone can create and view invoices; only managers can delete one.
-- =====================================================================

-- ---------- 1. PRICES ----------
alter table public.models
  add column if not exists price numeric(10,2) check (price is null or price >= 0);

-- ---------- 2. COMPANY DETAILS FOR INVOICES ----------
create table if not exists public.company_settings (
  id             int primary key default 1 check (id = 1),
  company_name   text,
  address        text,
  phone          text,
  email          text,
  website        text,
  bank_name      text,
  account_number text,
  sort_code      text,
  vat_number     text,
  company_number text,
  terms          text,
  updated_at     timestamptz not null default now()
);
insert into public.company_settings (id) values (1) on conflict (id) do nothing;

alter table public.company_settings enable row level security;
drop policy if exists "staff read company settings"   on public.company_settings;
drop policy if exists "manager edits company settings" on public.company_settings;
create policy "staff read company settings" on public.company_settings for select to authenticated using (true);
create policy "manager edits company settings" on public.company_settings for update to authenticated
  using (public.is_manager()) with check (public.is_manager());

drop trigger if exists company_settings_touch on public.company_settings;
create trigger company_settings_touch before update on public.company_settings
  for each row execute function public.touch_updated_at();

-- ---------- 3. INVOICES (no customer details) ----------
create table if not exists public.invoices (
  id           uuid primary key default gen_random_uuid(),
  number       int generated by default as identity (start with 1001) unique,
  invoice_date date not null default current_date,
  lines        jsonb not null,             -- [{description, qty, unit_price, vat_rate}]
  subtotal     numeric(12,2) not null,
  vat          numeric(12,2) not null,
  total        numeric(12,2) not null,
  created_by   uuid references public.profiles(id) default auth.uid(),
  created_at   timestamptz not null default now()
);

alter table public.invoices enable row level security;
drop policy if exists "staff read invoices"      on public.invoices;
drop policy if exists "staff create invoices"    on public.invoices;
drop policy if exists "manager deletes invoices" on public.invoices;
create policy "staff read invoices"   on public.invoices for select to authenticated using (true);
create policy "staff create invoices" on public.invoices for insert to authenticated
  with check (created_by = auth.uid());
create policy "manager deletes invoices" on public.invoices for delete to authenticated
  using (public.is_manager());

-- ---------- LIVE UPDATES ----------
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'invoices') then
    alter publication supabase_realtime add table public.invoices;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'company_settings') then
    alter publication supabase_realtime add table public.company_settings;
  end if;
end $$;
